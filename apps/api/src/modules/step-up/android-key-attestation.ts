/**
 * Android Key Attestation verification for Master Device enrollment.
 *
 * The phone generates its Master Device key in Android Keystore with an attestation challenge that
 * TrustID issued for this enrollment. Keystore returns a certificate chain whose leaf carries the
 * KeyDescription extension (OID 1.3.6.1.4.1.11129.2.1.17), signed up to a Google attestation root.
 * Verifying it is the only way the server can know — rather than trust the client's word — that:
 *   - the key lives in secure hardware (TEE or StrongBox) and cannot be exported,
 *   - it is an ECDSA P-256 signing key,
 *   - EVERY use requires a fresh strong biometric (no "auth once, sign for a while"),
 *   - it was generated by the genuine TrustID app (package + signing certificate),
 *   - on a device with verified boot and a locked bootloader,
 *   - for THIS enrollment (attestation challenge).
 * Anything unexpected is a rejection; nothing falls back to an unattested key.
 *
 * Schema: https://source.android.com/docs/security/features/keystore/attestation#schema
 */
import { createHash, X509Certificate } from "node:crypto";
import { GOOGLE_ATTESTATION_ROOTS_PEM } from "./android-attestation-roots.js";

export const KEY_DESCRIPTION_OID = "1.3.6.1.4.1.11129.2.1.17";

export const SECURITY_LEVEL = { SOFTWARE: 0, TRUSTED_ENVIRONMENT: 1, STRONG_BOX: 2 } as const;
export type SecurityLevelName = "software" | "tee" | "strongbox";
const LEVEL_NAME: Record<number, SecurityLevelName> = { 0: "software", 1: "tee", 2: "strongbox" };

/** KeyMint/Keymaster constants used by the policy. */
const KM = {
  PURPOSE_SIGN: 2,
  ALGORITHM_EC: 3,
  EC_CURVE_P256: 1,
  DIGEST_SHA256: 4,
  AUTH_BIOMETRIC: 2, // HardwareAuthenticatorType.FINGERPRINT (any Class 3 biometric)
  BOOT_VERIFIED: 0,
} as const;

/** AuthorizationList tags (context-specific, explicit). */
const TAG = {
  purpose: 1,
  algorithm: 2,
  keySize: 3,
  digest: 5,
  ecCurve: 10,
  noAuthRequired: 503,
  userAuthType: 504,
  authTimeout: 505,
  rootOfTrust: 704,
  attestationApplicationId: 709,
} as const;

export class AttestationRejected extends Error {
  constructor(readonly reason: string) {
    super(`Android key attestation rejected: ${reason}`);
    this.name = "AttestationRejected";
  }
}
const reject = (reason: string): never => {
  throw new AttestationRejected(reason);
};

/* ---------------------------------------------------------------- minimal strict DER reader */

type Tlv = { cls: number; constructed: boolean; tag: number; start: number; contentStart: number; end: number; bytes: Buffer };

function readTlv(buf: Buffer, offset: number): Tlv {
  if (offset + 2 > buf.length) reject("der_truncated");
  const first = buf[offset]!;
  const cls = first >> 6;
  const constructed = (first & 0x20) !== 0;
  let tag = first & 0x1f;
  let p = offset + 1;
  if (tag === 0x1f) {
    tag = 0;
    for (let i = 0; ; i++) {
      if (p >= buf.length || i > 4) reject("der_tag");
      const b = buf[p++]!;
      tag = (tag << 7) | (b & 0x7f);
      if ((b & 0x80) === 0) break;
    }
  }
  if (p >= buf.length) reject("der_truncated");
  let len = buf[p++]!;
  if (len & 0x80) {
    const n = len & 0x7f;
    if (n === 0 || n > 4 || p + n > buf.length) reject("der_length");
    len = 0;
    for (let i = 0; i < n; i++) len = len * 256 + buf[p++]!;
  }
  const end = p + len;
  if (end > buf.length) reject("der_truncated");
  return { cls, constructed, tag, start: offset, contentStart: p, end, bytes: buf };
}

function children(t: Tlv): Tlv[] {
  const out: Tlv[] = [];
  let p = t.contentStart;
  while (p < t.end) {
    const c = readTlv(t.bytes, p);
    out.push(c);
    p = c.end;
  }
  if (p !== t.end) reject("der_structure");
  return out;
}

const content = (t: Tlv) => t.bytes.subarray(t.contentStart, t.end);

function asInteger(t: Tlv): number {
  if (t.cls !== 0 || (t.tag !== 2 && t.tag !== 10)) reject("der_integer");
  const c = content(t);
  if (c.length === 0 || c.length > 6) reject("der_integer_size");
  let v = 0;
  for (const b of c) v = v * 256 + b;
  return v;
}

function oidString(c: Buffer): string {
  const parts = [Math.floor(c[0]! / 40), c[0]! % 40];
  let v = 0;
  for (let i = 1; i < c.length; i++) {
    v = v * 128 + (c[i]! & 0x7f);
    if ((c[i]! & 0x80) === 0) {
      parts.push(v);
      v = 0;
    }
  }
  return parts.join(".");
}

/** The KeyDescription extension's OCTET STRING value from a certificate's DER. */
function findExtension(certDer: Buffer, oid: string): Buffer | null {
  const cert = readTlv(certDer, 0);
  const [tbs] = children(cert);
  for (const field of children(tbs!)) {
    if (field.cls === 2 && field.tag === 3) {
      // [3] EXPLICIT Extensions
      const [extensions] = children(field);
      for (const ext of children(extensions!)) {
        const parts = children(ext);
        if (oidString(content(parts[0]!)) === oid) return Buffer.from(content(parts[parts.length - 1]!));
      }
    }
  }
  return null;
}

/* ---------------------------------------------------------------- KeyDescription parsing */

type AuthorizationList = Map<number, Tlv>;

function authorizationList(t: Tlv): AuthorizationList {
  const map: AuthorizationList = new Map();
  for (const item of children(t)) {
    if (item.cls !== 2) reject("authorization_list_tag");
    const [inner] = children(item); // explicit tagging
    map.set(item.tag, inner!);
  }
  return map;
}

function intSet(t: Tlv | undefined): number[] {
  if (!t) return [];
  return children(t).map(asInteger);
}

export type KeyDescription = {
  attestationVersion: number;
  attestationSecurityLevel: number;
  keyMintSecurityLevel: number;
  attestationChallenge: Buffer;
  softwareEnforced: AuthorizationList;
  hardwareEnforced: AuthorizationList;
};

export function parseKeyDescription(extensionValue: Buffer): KeyDescription {
  const seq = readTlv(extensionValue, 0);
  const f = children(seq);
  if (f.length < 8) reject("key_description_shape");
  return {
    attestationVersion: asInteger(f[0]!),
    attestationSecurityLevel: asInteger(f[1]!),
    keyMintSecurityLevel: asInteger(f[3]!),
    attestationChallenge: Buffer.from(content(f[4]!)),
    softwareEnforced: authorizationList(f[6]!),
    hardwareEnforced: authorizationList(f[7]!),
  };
}

type AppId = { packageNames: string[]; signatureDigests: string[] };

function parseAttestationApplicationId(t: Tlv): AppId {
  // OCTET STRING containing DER: SEQUENCE { SET OF AttestationPackageInfo, SET OF OCTET STRING }
  const inner = readTlv(Buffer.from(content(t)), 0);
  const [packages, digests] = children(inner);
  return {
    packageNames: children(packages!).map((p) => content(children(p)[0]!).toString("utf8")),
    signatureDigests: children(digests!).map((d) => content(d).toString("hex")),
  };
}

type RootOfTrust = { deviceLocked: boolean; verifiedBootState: number };

function parseRootOfTrust(t: Tlv): RootOfTrust {
  const f = children(t);
  return { deviceLocked: content(f[1]!)[0] !== 0, verifiedBootState: asInteger(f[2]!) };
}

/* ---------------------------------------------------------------- policy */

export type AttestationPolicy = {
  /** Pinned roots (PEM). Defaults to Google's. Tests inject their own. */
  trustedRootsPem?: readonly string[];
  /** Minimum security level of the key: "tee" (default) or "strongbox". */
  minSecurityLevel?: "tee" | "strongbox";
  /** Allowed TrustID Android package names. */
  packageNames: readonly string[];
  /** Allowed app signing certificate SHA-256 digests (lowercase hex). */
  signingCertSha256: readonly string[];
  /** Require verified boot with a locked bootloader (default true). */
  requireVerifiedBoot?: boolean;
  /** Serial numbers (lowercase hex) of revoked attestation certificates. */
  revokedSerials?: ReadonlySet<string>;
  now?: Date;
};

export type AttestationResult = {
  securityLevel: SecurityLevelName;
  attestationVersion: number;
  packageName: string;
  verifiedBoot: boolean;
  deviceLocked: boolean;
  perUseBiometric: true;
  chainRootSha256: string;
};

const spkiOf = (cert: X509Certificate) => cert.publicKey.export({ format: "der", type: "spki" }) as Buffer;

/**
 * Verify an Android Key Attestation chain (leaf first, base64 DER) for a Master Device key.
 * `publicKeySpki` is the key the phone is enrolling; `challenge` the bytes TrustID issued.
 */
export function verifyAndroidKeyAttestation(
  chainBase64: readonly string[],
  expect: { publicKeySpki: Buffer; challenge: Buffer },
  policy: AttestationPolicy,
): AttestationResult {
  if (!Array.isArray(chainBase64) || chainBase64.length < 2 || chainBase64.length > 10) reject("chain_length");
  let certs: X509Certificate[];
  try {
    certs = chainBase64.map((b64) => new X509Certificate(Buffer.from(b64, "base64")));
  } catch {
    return reject("chain_unparseable");
  }
  const now = policy.now ?? new Date();

  // Chain: each certificate signed by the next, all currently valid, ending at a pinned root.
  for (let i = 0; i < certs.length; i++) {
    const cert = certs[i]!;
    if (new Date(cert.validFrom) > now || new Date(cert.validTo) < now) reject(`certificate_validity_${i}`);
    const issuer = certs[i + 1] ?? cert;
    if (!cert.verify(issuer.publicKey)) reject(`chain_signature_${i}`);
    // Every certificate above the leaf must be a CA (signature checks alone do not enforce this).
    if (i > 0 && !cert.ca) reject(`not_a_ca_${i}`);
    if (policy.revokedSerials?.has(normalizeSerial(cert.serialNumber))) reject(`certificate_revoked_${i}`);
  }
  const root = certs[certs.length - 1]!;
  const trusted = (policy.trustedRootsPem ?? GOOGLE_ATTESTATION_ROOTS_PEM).map((p) => spkiOf(new X509Certificate(p)));
  const rootSpki = spkiOf(root);
  if (!trusted.some((t) => t.equals(rootSpki))) reject("untrusted_root");

  // The attested key is the key being enrolled.
  const leaf = certs[0]!;
  if (!spkiOf(leaf).equals(expect.publicKeySpki)) reject("key_mismatch");

  const ext = findExtension(Buffer.from(leaf.raw), KEY_DESCRIPTION_OID);
  if (!ext) return reject("no_key_description");
  const kd = parseKeyDescription(ext);

  if (!kd.attestationChallenge.equals(expect.challenge)) reject("challenge_mismatch");

  const minLevel = policy.minSecurityLevel === "strongbox" ? SECURITY_LEVEL.STRONG_BOX : SECURITY_LEVEL.TRUSTED_ENVIRONMENT;
  if (kd.attestationSecurityLevel < minLevel || kd.keyMintSecurityLevel < minLevel) {
    reject(`security_level_${LEVEL_NAME[kd.keyMintSecurityLevel] ?? "unknown"}`);
  }

  // Every property must be enforced by the secure hardware, not merely by Android.
  const hw = kd.hardwareEnforced;
  if (!intSet(hw.get(TAG.purpose)).includes(KM.PURPOSE_SIGN)) reject("not_a_signing_key");
  if (!hw.get(TAG.algorithm) || asInteger(hw.get(TAG.algorithm)!) !== KM.ALGORITHM_EC) reject("not_ec");
  if (!hw.get(TAG.ecCurve) || asInteger(hw.get(TAG.ecCurve)!) !== KM.EC_CURVE_P256) reject("not_p256");
  if (!intSet(hw.get(TAG.digest)).includes(KM.DIGEST_SHA256)) reject("no_sha256");
  if (hw.has(TAG.noAuthRequired) || kd.softwareEnforced.has(TAG.noAuthRequired)) reject("no_user_auth");
  const authType = hw.get(TAG.userAuthType) ?? reject("not_biometric_bound");
  if ((asInteger(authType) & KM.AUTH_BIOMETRIC) === 0) reject("not_biometric_bound");
  if ((asInteger(authType) & ~KM.AUTH_BIOMETRIC) !== 0) reject("auth_allows_device_credential");
  const timeout = hw.get(TAG.authTimeout) ?? kd.softwareEnforced.get(TAG.authTimeout);
  if (timeout && asInteger(timeout) !== 0) reject("auth_not_per_use");

  const rot = hw.get(TAG.rootOfTrust);
  if (!rot) return reject("no_root_of_trust");
  const boot = parseRootOfTrust(rot);
  const verifiedBoot = boot.verifiedBootState === KM.BOOT_VERIFIED;
  if ((policy.requireVerifiedBoot ?? true) && (!verifiedBoot || !boot.deviceLocked)) reject("unverified_boot");

  // The genuine TrustID app generated it (Android puts the app id in the software-enforced list).
  const appIdTlv = kd.softwareEnforced.get(TAG.attestationApplicationId) ?? hw.get(TAG.attestationApplicationId);
  if (!appIdTlv) return reject("no_application_id");
  const appId = parseAttestationApplicationId(appIdTlv);
  const packageName = appId.packageNames.find((p) => policy.packageNames.includes(p));
  if (!packageName || appId.packageNames.length !== 1) reject("wrong_package");
  const allowedDigests = policy.signingCertSha256.map((d) => d.toLowerCase().replace(/:/g, ""));
  if (!appId.signatureDigests.length || !appId.signatureDigests.every((d) => allowedDigests.includes(d))) reject("wrong_app_signer");

  return {
    securityLevel: LEVEL_NAME[kd.keyMintSecurityLevel]!,
    attestationVersion: kd.attestationVersion,
    packageName: packageName!,
    verifiedBoot,
    deviceLocked: boot.deviceLocked,
    perUseBiometric: true,
    chainRootSha256: createHash("sha256").update(rootSpki).digest("hex"),
  };
}

/* ---------------------------------------------------------------- revocation list */

/** Hex serial, lowercase, no leading zeros (the status list and X509Certificate differ in both). */
export function normalizeSerial(serial: string): string {
  return serial.toLowerCase().replace(/^0+(?=.)/, "");
}

let revocationCache: { at: number; serials: Set<string> } | null = null;

/**
 * Google's attestation certificate status list (https://android.googleapis.com/attestation/status).
 * Cached for an hour. Unreachable → throws: enrollment fails closed rather than skip the check.
 */
export async function fetchRevokedAttestationSerials(fetchImpl: typeof fetch = fetch): Promise<Set<string>> {
  if (revocationCache && Date.now() - revocationCache.at < 3600_000) return revocationCache.serials;
  const res = await fetchImpl("https://android.googleapis.com/attestation/status", { signal: AbortSignal.timeout(8000) });
  if (!res.ok) throw new AttestationRejected("revocation_list_unavailable");
  const body = (await res.json()) as { entries?: Record<string, { status?: string }> };
  const serials = new Set(
    Object.entries(body.entries ?? {})
      .filter(([, v]) => (v.status ?? "").toUpperCase() === "REVOKED")
      .map(([k]) => normalizeSerial(k)),
  );
  revocationCache = { at: Date.now(), serials };
  return serials;
}

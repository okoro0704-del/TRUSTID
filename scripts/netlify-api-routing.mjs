#!/usr/bin/env node
/**
 * Netlify: route /api/* to the TrustID API of THIS deployment's environment, and nothing else.
 *
 * netlify.toml redirects apply to every Netlify site and context, so the /api proxy is generated
 * here, at build time, into the publish directory's `_redirects` (which Netlify applies before
 * netlify.toml). netlify.toml itself only answers /api/* with 404: if this step did not run, the
 * API is unreachable rather than pointed somewhere by default.
 *
 *   Production site (SITE_NAME=trustedid, CONTEXT=production) → the production API only.
 *   TRUSTID_DEPLOY_ENV=staging → TRUSTID_API_PROXY_ORIGIN (required, https, never production).
 *   Deploy previews / branch deploys → TRUSTID_PREVIEW_API_ORIGIN if set (never production),
 *                                      otherwise no API at all.
 *   Anything else → build fails. There is no production fallback.
 *
 * Usage (Netlify build command): node scripts/netlify-api-routing.mjs apps/web/dist
 */
import { mkdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { pathToFileURL } from "node:url";

export const PRODUCTION_SITE_NAME = "trustedid";
export const PRODUCTION_API_ORIGIN = "https://lucid-integrity-production.up.railway.app";
const PRODUCTION_API_HOSTS = new Set(["lucid-integrity-production.up.railway.app", "trustedid.netlify.app"]);

export class RoutingError extends Error {}

function apiOrigin(value, name) {
  let url;
  try {
    url = new URL(String(value ?? "").trim());
  } catch {
    throw new RoutingError(`${name} must be an https origin (got ${value ? "an invalid URL" : "nothing"})`);
  }
  if (url.protocol !== "https:" || url.pathname !== "/" || url.search || url.hash || url.username || url.password) {
    throw new RoutingError(`${name} must be a bare https origin such as https://api.staging.example`);
  }
  if (PRODUCTION_API_HOSTS.has(url.hostname)) {
    throw new RoutingError(`${name} points at production (${url.hostname}); staging and previews may never use the production API`);
  }
  return url.origin;
}

/** Decide the /api route for a Netlify build environment. Throws RoutingError when it must not build. */
export function resolveApiRouting(env) {
  const context = env.CONTEXT ?? "";
  const site = env.SITE_NAME ?? "";
  const deployEnv = (env.TRUSTID_DEPLOY_ENV ?? "").trim();

  if (deployEnv && deployEnv !== "staging" && deployEnv !== "production") {
    throw new RoutingError(`TRUSTID_DEPLOY_ENV must be "staging" or "production", not "${deployEnv}"`);
  }
  if (deployEnv === "staging") {
    if (site === PRODUCTION_SITE_NAME) throw new RoutingError("TRUSTID_DEPLOY_ENV=staging is set on the production site");
    return { environment: "staging", target: apiOrigin(env.TRUSTID_API_PROXY_ORIGIN, "TRUSTID_API_PROXY_ORIGIN") };
  }
  if (context === "deploy-preview" || context === "branch-deploy") {
    if (env.TRUSTID_PREVIEW_API_ORIGIN?.trim()) {
      return { environment: "preview", target: apiOrigin(env.TRUSTID_PREVIEW_API_ORIGIN, "TRUSTID_PREVIEW_API_ORIGIN") };
    }
    return { environment: "preview", target: null };
  }
  if (site === PRODUCTION_SITE_NAME && context === "production") {
    const override = env.TRUSTID_API_PROXY_ORIGIN?.trim();
    if (override && override.replace(/\/$/, "") !== PRODUCTION_API_ORIGIN) {
      throw new RoutingError("The production site may only proxy to the production API");
    }
    return { environment: "production", target: PRODUCTION_API_ORIGIN };
  }
  throw new RoutingError(
    `No TrustID API routing for site "${site || "?"}" context "${context || "?"}": set TRUSTID_DEPLOY_ENV=staging and TRUSTID_API_PROXY_ORIGIN`,
  );
}

/** The `_redirects` file for a routing decision. */
export function redirectsFor(routing) {
  const lines = [`# Generated by scripts/netlify-api-routing.mjs (${routing.environment}). Do not edit.`];
  if (routing.environment === "production") {
    // Keep the alias host redirecting (these rules must precede /api, as in netlify.toml).
    lines.push(
      "https://trustid.getlifeos.app/sw.js  /sw-retire.js  200!",
      "https://trustid.getlifeos.app/*  https://trustedid.netlify.app/:splat  301!",
      "http://trustid.getlifeos.app/*  https://trustedid.netlify.app/:splat  301!",
    );
  }
  if (routing.target) {
    lines.push(`/api/*  ${routing.target}/:splat  200!`, `/api  ${routing.target}/  200!`);
  } else {
    lines.push("/api/*  /404.html  404!", "/api  /404.html  404!");
  }
  return `${lines.join("\n")}\n`;
}

function main() {
  const publishDir = process.argv[2];
  if (!publishDir) {
    console.error("usage: node scripts/netlify-api-routing.mjs <publish dir>");
    process.exit(2);
  }
  let routing;
  try {
    routing = resolveApiRouting(process.env);
  } catch (err) {
    console.error(`netlify-api-routing: ${err.message}`);
    process.exit(1);
  }
  mkdirSync(publishDir, { recursive: true });
  writeFileSync(join(publishDir, "_redirects"), redirectsFor(routing));
  console.log(`netlify-api-routing: ${routing.environment} → ${routing.target ?? "no API (404)"}`);
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? "").href) main();
